#!/usr/bin/env bash
# Build the SmartVA scoring library for iOS (device arm64 and Apple-silicon simulator arm64) with embedded reference data,
# the iOS twin of scripts/build-smartva-android.sh.
#
# The crate declares crate-type = ["rlib", "cdylib"]; iOS apps cannot ship a loose dylib from a pod, so this uses
# `cargo rustc --crate-type staticlib`, which overrides the crate type on the command line and leaves the
# vendor/smartva-analyze submodule untouched.
#
# Output (OUT_DIR, default private/generated/smartva-ios, git-ignored):
#   <target>/libsmartva_rust.a                      the static library per Rust target
#   frameworks/<slice>/SmartvaRust.framework        a static framework per slice: the archive as the binary, the C header
#                                                   for the three functions the app calls, and a module map, so Swift
#                                                   can `import SmartvaRust`
#   SmartvaRust.xcframework                         macOS only: xcodebuild -create-xcframework over the two frameworks
# modules/digitva-smartva/scripts/stage-engine.js (stageSmartvaIos) copies the xcframework into the module for a Plus build.
#
# Any host with the two Rust targets builds the archives and frameworks (verified on Linux x64). The xcframework needs
# Xcode's xcodebuild: on Linux the script stops after the frameworks and says so.
# Usage: scripts/build-smartva-ios.sh [OUT_DIR]
set -euo pipefail

[[ $# -le 1 ]] || { echo "usage: $0 [OUT_DIR]" >&2; exit 2; }
repo_root="$(cd "$(dirname "$0")/.." && pwd)"
out_dir=${1:-"$repo_root/private/generated/smartva-ios"}
mkdir -p "$out_dir" && out_dir="$(cd "$out_dir" && pwd)"
manifest="$repo_root/vendor/smartva-analyze/rust/Cargo.toml"
[[ -f "$manifest" ]] || { echo "SmartVA source missing: git submodule update --init vendor/smartva-analyze" >&2; exit 1; }

# The same floor as the Expo SDK's pods (platform :ios, '16.4' in the generated Podfile).
min_ios=16.4
targets=(aarch64-apple-ios aarch64-apple-ios-sim)
installed="$(rustup target list --installed)"
for target in "${targets[@]}"; do
  grep -qx "$target" <<<"$installed" || { echo "install the Rust target first: rustup target add $target" >&2; exit 1; }
done

export CARGO_TARGET_DIR="$repo_root/private/generated/smartva-ios-target"
export IPHONEOS_DEPLOYMENT_TARGET=$min_ios
export IPHONESIMULATOR_DEPLOYMENT_TARGET=$min_ios
for target in "${targets[@]}"; do
  cargo rustc --manifest-path "$manifest" --locked --release --lib --target "$target" \
    --no-default-features --features mobile-core --crate-type staticlib
  mkdir -p "$out_dir/$target"
  cp "$CARGO_TARGET_DIR/$target/release/libsmartva_rust.a" "$out_dir/$target/libsmartva_rust.a"
done

if command -v llvm-nm >/dev/null; then nm_tool=llvm-nm; else nm_tool=nm; fi
if command -v sha256sum >/dev/null; then sum=(sha256sum); else sum=(shasum -a 256); fi

# Mach-O prefixes C symbols with "_". The app calls exactly these three; fail early if the archive lacks any.
for target in "${targets[@]}"; do
  archive="$out_dir/$target/libsmartva_rust.a"
  # Rust's std members carry embedded bitcode that an older llvm-nm cannot parse; it still lists every member it can
  # read (ours included) and exits non-zero, so its status is ignored and the symbol check below decides.
  symbols="$({ "$nm_tool" -g --defined-only "$archive" 2>/dev/null || true; } | awk '{print $NF}')"
  for symbol in _smartva_version _smartva_score_json _smartva_free_string; do
    grep -qx "$symbol" <<<"$symbols" || { echo "$archive does not define $symbol" >&2; exit 1; }
  done
done

# The C ABI of vendor/smartva-analyze/rust/src/lib.rs, limited to what DigitvaSmartvaModule.swift calls.
header_text='/* Generated by scripts/build-smartva-ios.sh: the SmartVA C ABI (vendor/smartva-analyze/rust/src/lib.rs) used by DigitVA. */
#ifndef SMARTVA_RUST_H
#define SMARTVA_RUST_H

#ifdef __cplusplus
extern "C" {
#endif

/* Static, NUL-terminated version banner. Do not free. */
const char *smartva_version(void);

/* 0 on success with *result_json_out set (free with smartva_free_string); non-zero with *error_out set otherwise. */
int smartva_score_json(const char *json_payload, const char *country, int hiv, int malaria, int hce, int freetext,
                       int extended, char **result_json_out, char **error_out);

/* Frees a string returned by smartva_score_json. NULL is ignored. */
void smartva_free_string(char *ptr);

#ifdef __cplusplus
}
#endif

#endif /* SMARTVA_RUST_H */'

framework_plist="<?xml version=\"1.0\" encoding=\"UTF-8\"?>
<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">
<plist version=\"1.0\">
<dict>
  <key>CFBundleDevelopmentRegion</key><string>en</string>
  <key>CFBundleExecutable</key><string>SmartvaRust</string>
  <key>CFBundleIdentifier</key><string>org.digitva.SmartvaRust</string>
  <key>CFBundleInfoDictionaryVersion</key><string>6.0</string>
  <key>CFBundleName</key><string>SmartvaRust</string>
  <key>CFBundlePackageType</key><string>FMWK</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>MinimumOSVersion</key><string>$min_ios</string>
</dict>
</plist>"

rm -rf "$out_dir/frameworks"
frameworks=()
for target in "${targets[@]}"; do
  framework="$out_dir/frameworks/$target/SmartvaRust.framework"
  mkdir -p "$framework/Headers" "$framework/Modules"
  cp "$out_dir/$target/libsmartva_rust.a" "$framework/SmartvaRust"
  printf '%s\n' "$header_text" > "$framework/Headers/SmartvaRust.h"
  printf 'framework module SmartvaRust {\n  umbrella header "SmartvaRust.h"\n  export *\n  module * { export * }\n}\n' \
    > "$framework/Modules/module.modulemap"
  printf '%s\n' "$framework_plist" > "$framework/Info.plist"
  frameworks+=(-framework "$framework")
done

for target in "${targets[@]}"; do
  archive="$out_dir/$target/libsmartva_rust.a"
  echo "archive: $archive ($(wc -c < "$archive" | tr -d ' ') bytes)"
  "${sum[@]}" "$archive"
done

xcframework="$out_dir/SmartvaRust.xcframework"
if [[ "$(uname -s)" != Darwin ]] || ! command -v xcodebuild >/dev/null; then
  echo "frameworks: $out_dir/frameworks (built)"
  echo "xcframework: NOT built: xcodebuild -create-xcframework needs macOS with Xcode. Run this script on a Mac to finish." >&2
  exit 0
fi

rm -rf "$xcframework"
xcodebuild -create-xcframework "${frameworks[@]}" -output "$xcframework"
echo "xcframework: $xcframework"
# One digest over every file, in a fixed order, for the build log.
(cd "$out_dir" && find SmartvaRust.xcframework -type f | LC_ALL=C sort | xargs "${sum[@]}" | "${sum[@]}" | awk '{print "xcframework sha256 (files): " $1}')
