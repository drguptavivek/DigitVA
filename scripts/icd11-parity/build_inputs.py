"""Write the one request list that both the phone harness and the container runner read.

Sections, in this order (each line "<type>\t<id>\t<argument>"):
  D  our synthetic certificates (make_certificates.py output; OURS.jsonl, e.g. datasets/hash-synthetic-10k/certificates.jsonl.gz unpacked)
  D  our earlier DORIS suite (datasets/clinical-variants-10k): 10,000 inputs and 10 erroneous edge cases (generated by the DigitVA team
     on 2026-10-24; fixture hashes checked first)
  D  malformed requests: invalid JSON, null, an empty object, an array, an empty string
  G  the engine's one call (digitva_icd11_call) as "<id>\t<op>\t<json>": the search texts of queries.json (`search`, q only), its code-info
     inputs (`codeinfo`, code only; plain, postcoordinated, malformed), then the requests of calls.json (search with options,
     codeinfo options, entity, foundation entity, and the bounds: search `limit` with and without flatResults, refused `include=descendant`)
  G  golden: every WHO REST request recorded in scripts/icd11-golden/fixtures (the reads the DigitVA server made for the owner-approved
     DORIS, postcoordination and search corpora), turned back into engine calls by the inverse of run_container.rest and checked by round
     trip; its DORIS and CoDEdit POSTs are D lines (one line runs both)
  G  sweep: datasets/api-sweep/calls.jsonl.gz, the reads the coding screen makes for every code of our datasets (make_sweep.py)
  Every D line is sent as DORIS then CoDEdit with the text as the call's `certificate` argument (phone_harness.c), so everything goes through the one call.

SUITE_FIXTURES_DIR holds inputs_all.jsonl and edge_inputs.jsonl, each plain or gzipped as NAME.gz (plain wins); the committed
datasets/clinical-variants-10k works as it is. It may be "-" for a targeted run: the earlier suite's 10,010 inputs are then left out (pair it with a short OURS.jsonl:
make_certificates.py OURS.jsonl 200).

The optional fourth argument lists the extra sections to add, comma-separated: golden, sweep (eval.sh: quick = golden, full = golden,sweep).

usage: python3 scripts/icd11-parity/build_inputs.py OUT.tsv OURS.jsonl SUITE_FIXTURES_DIR|- [golden][,sweep]
"""
import gzip
import hashlib
import json
import pathlib
import re
import sys
import urllib.parse

import run_container

HERE = pathlib.Path(__file__).parent
# tests/fixtures/hashes.json of our suite (ICD11-DORIS-kotlin-rust-source.zip, icd-offline-0.3, 2026-10-24).
SUITE = {
    "inputs_all.jsonl": "7d374562b6149dcd0a06454bc859e3cd1a08d3286a8089ea9ef43106527ee0ae",
    "edge_inputs.jsonl": "3d17ac57b3fcfe349f32031583be6fd9710c7c0a22049b7cb8ea8142bcc89c2f",
}
GOLDEN = HERE.parent / "icd11-golden" / "fixtures"
SWEEP = HERE / "datasets" / "api-sweep" / "calls.jsonl.gz"
MALFORMED = [("not-json", "this is not json"), ("null", "null"), ("empty-object", "{}"), ("array", "[]"),
             ("empty-string", "")]


def fixture(directory, name):
    """Bytes of NAME or NAME.gz in the directory (plain wins); the pinned sha256 is that of the plain file."""
    plain = directory / name
    return plain.read_bytes() if plain.exists() else gzip.decompress((directory / f"{name}.gz").read_bytes())


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def canonical(op, args):
    """Sort key and identity of a request: the op and its arguments with keys in order."""
    return op + "\t" + json.dumps(args, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def engine_call(method, path, body):
    """The engine call (op, args) whose REST request is `method path body`: the inverse of run_container.rest. None when nothing maps."""
    path, _, text = path.partition("?")
    extra = {}
    for key, value in urllib.parse.parse_qsl(text, keep_blank_values=True):
        if key in extra or key not in ("flexiblemode", "convertToTerminalCodes", "include") or (key != "include" and value not in ("true", "false")):
            return None
        extra[key] = value if key == "include" else value == "true"
    release = run_container.RELEASE + "/"
    if method == "POST" and path == release + "mms/search" and not extra:
        pairs = urllib.parse.parse_qsl(body or "", keep_blank_values=True, strict_parsing=True)
        args = {k: (v == "true" if v in ("true", "false") else v) for k, v in pairs}
        return ("search", args) if len(args) == len(pairs) else None
    if method == "POST" and path in (release + "doris", release + "codedit") and not extra:
        return ("D", body) if body else None
    if method != "GET":
        return None
    if path.startswith(release + "mms/codeinfo/"):
        return "codeinfo", {"code": urllib.parse.unquote(path[len(release + "mms/codeinfo/"):]), **extra}
    found = re.fullmatch(re.escape(release) + r"mms/(\d+)(?:/(unspecified|other))?", path)
    if found:
        return "entity", {"id": found[1], **({"residual": found[2]} if found[2] else {}), **extra}
    found = re.fullmatch(r"icd/entity/(\d+)", path)
    return ("foundation_entity", {"id": found[1], **extra}) if found else None


def golden_requests():
    """The deduplicated golden requests, sorted by canonical key: ([(op, args)], [certificate text]), after a round trip of every recorded
    request through run_container.rest. Stops with the list of requests that do not map or do not come back identical."""
    recorded = set()
    for path in sorted(GOLDEN.glob("*/*.json")):
        for entry in json.loads(path.read_text(encoding="utf-8"))["who"].values():
            body = entry.get("request_body")
            recorded.add((entry["method"], entry["path"], body if isinstance(body, str) else None if body is None else compact(body)))
    calls, certificates, bad = {}, {}, []
    for method, path, body in sorted(recorded, key=lambda r: (r[0], r[1], r[2] or "")):
        found = engine_call(method, path, body)
        if found is None:
            bad.append(f"no mapping: {method} {path}")
        elif found[0] == "D":
            if "\t" in found[1] or "\n" in found[1]:
                bad.append(f"certificate holds a tab or newline: {path}")
            certificates[found[1]] = True
        else:
            again = run_container.rest(*found)
            if (again[0], again[1], again[2].decode() if again[2] is not None else None) != (method, path, body):
                bad.append(f"round trip differs: {method} {path} -> {again[:3]}")
            calls[canonical(*found)] = found
    if bad:
        raise SystemExit(f"golden: {len(bad)} of {len(recorded)} recorded requests do not round-trip:\n" + "\n".join(bad[:40]))
    return [calls[key] for key in sorted(calls)], sorted(certificates)


def golden_sha256():
    """Hash of the derived golden request list (what the run sends) and of the golden manifest it was recorded under."""
    calls, certificates = golden_requests()
    text = "\n".join([canonical(*c) for c in calls] + certificates)
    return {"requests_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(), "calls": len(calls), "certificates": len(certificates),
            "manifest_sha256": hashlib.sha256((GOLDEN / "manifest.json").read_bytes()).hexdigest()}


def submission(row):
    value = row["submission"]
    return value if isinstance(value, str) else compact(value)


def main():
    out_path, ours, fixtures = sys.argv[1], pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
    extra = sys.argv[4].split(",") if len(sys.argv) > 4 and sys.argv[4] else []
    if set(extra) - {"golden", "sweep"}:
        raise SystemExit("extra sections: golden, sweep")
    suite = str(fixtures) != "-"
    for name, digest in SUITE.items() if suite else []:
        actual = hashlib.sha256(fixture(fixtures, name)).hexdigest()
        if actual != digest:
            raise SystemExit(f"{name}: sha256 {actual} is not the pinned {digest}")
    queries = json.loads((HERE / "queries.json").read_text())
    calls = json.loads((HERE / "calls.json").read_text())["calls"]
    counts = {}
    with open(out_path, "w", encoding="utf-8") as out:
        def put(kind, section, ident, arg):
            if arg.count("\t") != (1 if kind == "G" else 0) or "\n" in arg:
                raise SystemExit(f"{ident}: argument holds a tab or newline")
            out.write(f"{kind}\t{ident}\t{arg}\n")
            counts[section] = counts.get(section, 0) + 1

        ours_rows = [json.loads(line) for line in ours.read_text(encoding="utf-8").splitlines()]
        for row in ours_rows:
            put("D", "ours", f"ours/{row['id']}", compact(row["certificate"]))
        for name, section in [("inputs_all.jsonl", "suite"), ("edge_inputs.jsonl", "edge")] if suite else []:
            for line in fixture(fixtures, name).decode("utf-8").splitlines():
                row = json.loads(line)
                put("D", section, f"{section}/{row['id']}", submission(row))
        for ident, text in MALFORMED:
            put("D", "malformed", f"malformed/{ident}", text)
        for n, text in enumerate(queries["search"]):
            put("G", "search", f"search/{n:03d}", f"search\t{compact({'q': text})}")
        for n, code in enumerate(queries["codeinfo"]):
            put("G", "codeinfo", f"codeinfo/{n:03d}", f"codeinfo\t{compact({'code': code})}")
        for n, call in enumerate(calls):
            put("G", "call", f"call/{n:03d}-{call['op']}", f"{call['op']}\t{compact(call['args'])}")
        if "golden" in extra:
            calls_g, certificates = golden_requests()
            for n, text in enumerate(certificates):
                put("D", "golden", f"golden/cert-{n:04d}", text)
            for n, (op, args) in enumerate(calls_g):
                put("G", "golden", f"golden/{n:04d}-{op}", f"{op}\t{compact(args)}")
        if "sweep" in extra:
            for n, line in enumerate(gzip.decompress(SWEEP.read_bytes()).decode("utf-8").splitlines()):
                row = json.loads(line)
                put("G", "sweep", f"sweep/{n:05d}-{row['op']}", f"{row['op']}\t{compact(row['args'])}")
    print(", ".join(f"{k} {v}" for k, v in counts.items()))


if __name__ == "__main__":
    main()
