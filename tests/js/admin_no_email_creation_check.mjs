// Run: node tests/js/admin_no_email_creation_check.mjs
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../../mobile/digitva-collect/package.json', import.meta.url));
const { JSDOM } = require('jsdom');
const template = readFileSync(new URL('../../app/templates/admin/panels/users.html', import.meta.url), 'utf8');
const source = readFileSync(new URL('../../app/static/js/admin/users_panel.js', import.meta.url), 'utf8');
const dom = new JSDOM(template.replace(/data-languages="[^"]*"/, 'data-languages="[]"'), {runScripts: 'outside-only', url: 'http://localhost'});
const w = dom.window, requests = [];
const el = id => w.document.getElementById('user-' + id);
const tick = () => new Promise(resolve => setImmediate(resolve));
w.$ = () => ({val(value) { if (value === undefined) return ['english']; return this; }, trigger() {return this;}, append() {}, select2() {}});
w.fetch = (url, options) => new Promise((resolve, reject) => requests.push({url, options, resolve(data) {resolve({ok: true, json: async () => data});}, reject}));
w.eval(source);
requests.shift().resolve({users: [{user_id: 'email-user', email: 'person@example.com', name: 'Person', status: 'active', languages: ['english']}]});
await tick();
el('show-form-btn').click();
el('name-input').value = 'Email Person';
el('email-input').value = 'person@example.com';
el('email-confirm-input').value = 'person@example.com';
el('phone-input').value = '123';
el('submit-btn').click();
assert.equal(requests.length, 0, 'invalid optional mobile never reaches server');
assert.match(el('form-error').textContent, /10-digit/);
el('email-input').value = 'stale@example.com';
el('email-confirm-input').value = 'stale@example.com';
el('no-email-input').checked = true;
el('no-email-input').dispatchEvent(new w.Event('change'));
assert.equal(el('email-input').value, '');
assert.equal(el('email-confirm-input').disabled, true);
assert.equal(el('phone-input').required, true);
assert.equal(el('phone-input').maxLength, 10);
assert.equal(el('phone-confirm-input').required, true);
el('name-input').value = 'Mobile Person';
el('phone-input').value = '9876543210';
el('phone-confirm-input').value = '9876543211';
el('submit-btn').click();
assert.equal(requests.length, 0, 'mismatch never reaches server');
assert.match(el('form-error').textContent, /does not match/);
el('phone-confirm-input').value = '9876543210';
el('submit-btn').click();
const creation = requests.shift();
const payload = JSON.parse(creation.options.body);
assert.equal(payload.no_email, true);
assert.equal(payload.email, '');
assert.equal(payload.phone_confirm, '9876543210');
creation.resolve({sign_in_code: '482917'});
await tick();
assert.match(el('code-box').textContent, /482917/, 'code shown before refresh returns');
requests.shift().reject(new Error('Refresh unavailable'));
await tick();
assert.match(el('code-box').textContent, /482917/, 'refresh failure retains code');
el('show-form-btn').click();
assert.equal(el('no-email-input').checked, false);
assert.equal(el('phone-confirm-input').value, '');
assert.equal(el('email-input').disabled, false);
assert.equal(el('phone-input').required, false);
el('cancel-btn').click();
// Reload the table after its deliberately failed refresh to exercise edit mode.
el('show-inactive').dispatchEvent(new w.Event('change'));
requests.shift().resolve({users: [{user_id: 'email-user', email: 'person@example.com', name: 'Person', status: 'active', languages: ['english']}]});
await tick();
w.document.querySelector('.user-edit-btn').click();
assert.equal(el('no-email-row').classList.contains('d-none'), true);
assert.equal(el('phone-confirm-input').disabled, true);
assert.equal(el('email-input').value, 'person@example.com');
assert.equal(el('email-input').disabled, false);
console.log('OK: no-email toggle, confirmation, reset, edit isolation and code retention');
